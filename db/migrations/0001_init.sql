CREATE TABLE IF NOT EXISTS students (
  id          TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  email       TEXT,
  whatsapp    TEXT,
  city        TEXT,
  source      TEXT NOT NULL DEFAULT 'Placement test',
  stage       TEXT NOT NULL DEFAULT 'baru' CHECK (stage IN ('baru', 'dihubungi', 'konsultasi', 'terdaftar', 'lepas')),
  program_id  TEXT,
  duration_id TEXT,
  period_id   TEXT,
  class_id    TEXT,
  created_at  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_students_whatsapp ON students (whatsapp) WHERE whatsapp IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_students_email ON students (email);
CREATE INDEX IF NOT EXISTS idx_students_stage ON students (stage, created_at);

CREATE TABLE IF NOT EXISTS attempts (
  id               TEXT PRIMARY KEY,
  test_key         TEXT NOT NULL DEFAULT 'placement',
  student_id       TEXT,
  question_ids     TEXT,
  time_mode        TEXT NOT NULL DEFAULT 'total',
  limit_seconds    INTEGER,
  max_violations   INTEGER NOT NULL DEFAULT 3,
  pass_score       INTEGER,
  passed           INTEGER,
  invite_id        TEXT,
  started_at       BIGINT NOT NULL,
  expires_at       BIGINT NOT NULL,
  submitted_at     BIGINT,
  status           TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'submitted')),
  score            INTEGER,
  total            INTEGER NOT NULL DEFAULT 25,
  level_key        TEXT,
  timed_out        INTEGER NOT NULL DEFAULT 0,
  name             TEXT,
  email            TEXT,
  whatsapp         TEXT,
  consent_version  TEXT NOT NULL,
  consent_at       BIGINT NOT NULL,
  violations       INTEGER NOT NULL DEFAULT 0,
  violation_log    TEXT,
  duration_seconds INTEGER,
  email_sent_at    BIGINT,
  email_status     TEXT,
  user_agent       TEXT,
  country          TEXT,
  voided_at        BIGINT,
  voided_by        TEXT,
  void_reason      TEXT
);
CREATE INDEX IF NOT EXISTS idx_attempts_email ON attempts (email);
CREATE INDEX IF NOT EXISTS idx_attempts_status ON attempts (status, started_at);
CREATE INDEX IF NOT EXISTS idx_attempts_test ON attempts (test_key, started_at);
CREATE INDEX IF NOT EXISTS idx_attempts_student ON attempts (student_id);

CREATE TABLE IF NOT EXISTS answers (
  attempt_id  TEXT NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL,
  choice      TEXT,
  is_correct  INTEGER NOT NULL DEFAULT 0,
  answer_key  TEXT,
  PRIMARY KEY (attempt_id, question_id)
);

CREATE TABLE IF NOT EXISTS activities (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  at         BIGINT NOT NULL,
  type       TEXT NOT NULL,
  text       TEXT NOT NULL,
  by_name    TEXT,
  meta       TEXT
);
CREATE INDEX IF NOT EXISTS idx_activities_student ON activities (student_id, at);

CREATE TABLE IF NOT EXISTS tutors (
  id         TEXT PRIMARY KEY,
  name       TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tutors_name ON tutors (lower(name));

CREATE TABLE IF NOT EXISTS programs (
  id         TEXT PRIMARY KEY,
  name       TEXT NOT NULL,
  mode       TEXT NOT NULL,
  status     TEXT NOT NULL DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif')),
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_programs_name ON programs (lower(name));

CREATE TABLE IF NOT EXISTS program_durations (
  id         TEXT PRIMARY KEY,
  program_id TEXT NOT NULL REFERENCES programs(id) ON DELETE CASCADE,
  position   INTEGER NOT NULL,
  label      TEXT NOT NULL,
  days       INTEGER NOT NULL,
  price      BIGINT
);

CREATE TABLE IF NOT EXISTS program_tutors (
  program_id TEXT NOT NULL REFERENCES programs(id) ON DELETE CASCADE,
  tutor_id   TEXT NOT NULL REFERENCES tutors(id) ON DELETE CASCADE,
  PRIMARY KEY (program_id, tutor_id)
);

CREATE TABLE IF NOT EXISTS periods (
  id         TEXT PRIMARY KEY,
  start_date TEXT NOT NULL UNIQUE,
  note       TEXT,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS classes (
  id         TEXT PRIMARY KEY,
  code       TEXT NOT NULL,
  program_id TEXT NOT NULL REFERENCES programs(id),
  period_id  TEXT NOT NULL REFERENCES periods(id),
  tutor_id   TEXT NOT NULL REFERENCES tutors(id),
  capacity   INTEGER NOT NULL DEFAULT 20,
  created_at BIGINT NOT NULL,
  UNIQUE (period_id, code)
);

CREATE TABLE IF NOT EXISTS invites (
  id         TEXT PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE,
  student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  test_key   TEXT NOT NULL CHECK (test_key IN ('pre', 'post')),
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  used_at    BIGINT,
  attempt_id TEXT,
  created_by TEXT
);
CREATE INDEX IF NOT EXISTS idx_invites_student ON invites (student_id);

CREATE TABLE IF NOT EXISTS wa_messages (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id          TEXT,
  to_number           TEXT NOT NULL,
  text                TEXT NOT NULL,
  status              TEXT NOT NULL,
  provider_message_id TEXT,
  error               TEXT,
  created_at          BIGINT NOT NULL,
  created_by          TEXT
);
CREATE INDEX IF NOT EXISTS idx_wa_student ON wa_messages (student_id, created_at);

CREATE TABLE IF NOT EXISTS admin_users (
  id             TEXT PRIMARY KEY,
  email          TEXT NOT NULL UNIQUE,
  name           TEXT NOT NULL,
  role           TEXT NOT NULL DEFAULT 'admin',
  password_hash  TEXT NOT NULL,
  password_salt  TEXT NOT NULL,
  password_iter  INTEGER NOT NULL,
  failed_logins  INTEGER NOT NULL DEFAULT 0,
  locked_until   BIGINT,
  last_login_at  BIGINT,
  active         INTEGER NOT NULL DEFAULT 1,
  created_at     BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS admin_sessions (
  token_hash TEXT PRIMARY KEY,
  user_id    TEXT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  user_agent TEXT
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON admin_sessions (user_id);
