-- IELTS mockup speaking: the examiner video interview in three parts, one recording per question,
-- scored by Speechace in the background. The speaking band joins the overall band as the fourth
-- skill once every answer is graded.

CREATE TABLE IF NOT EXISTS speaking_answers (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id      TEXT NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
  part            INTEGER NOT NULL,
  prompt_no       INTEGER NOT NULL,
  prompt          TEXT NOT NULL,
  video_url       TEXT,
  audio           BYTEA,
  audio_mime      TEXT,
  audio_bytes     INTEGER,
  duration_seconds INTEGER,
  status          TEXT NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending', 'grading', 'graded', 'failed', 'manual', 'skipped')),
  tries           INTEGER NOT NULL DEFAULT 0,
  next_attempt_at BIGINT NOT NULL DEFAULT 0,
  lease_until     BIGINT NOT NULL DEFAULT 0,
  transcript      TEXT,
  scores          TEXT,
  ielts_overall   NUMERIC(3,1),
  response        TEXT,
  needs_review    INTEGER NOT NULL DEFAULT 0,
  error           TEXT,
  created_at      BIGINT NOT NULL,
  graded_at       BIGINT,
  UNIQUE (attempt_id, part, prompt_no)
);
CREATE INDEX IF NOT EXISTS idx_speaking_answers_status ON speaking_answers (status, next_attempt_at);
CREATE INDEX IF NOT EXISTS idx_speaking_answers_attempt ON speaking_answers (attempt_id);

ALTER TABLE attempts ADD COLUMN IF NOT EXISTS speaking_status TEXT;
ALTER TABLE attempts ADD COLUMN IF NOT EXISTS speaking_error TEXT;

-- The full mock now includes the speaking interview: 155 minutes for Listening, Reading, and
-- Writing, plus room for the speaking parts.
UPDATE tests SET speaking_enabled = 1, total_seconds = 10500 WHERE key = 'ielts-mockup';
